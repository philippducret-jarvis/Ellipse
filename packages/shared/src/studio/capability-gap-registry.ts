export function summarizeGapRegistry() {
  const byStatus = { missing: 0, stub: 0, partial: 0, production_ready: 0 };
  let maturitySum = 0;
  for (const cap of STUDIO_CAPABILITY_GAPS) {
    byStatus[cap.status]++;
    maturitySum += cap.maturity_pct;
  }
  return {
    total_capabilities: STUDIO_CAPABILITY_GAPS.length,
    engines: EVOLUTION_ENGINES.length,
    average_maturity_pct: Math.round(maturitySum / STUDIO_CAPABILITY_GAPS.length),
    by_status: byStatus,
    p0_count: STUDIO_CAPABILITY_GAPS.filter((c) => c.priority === 'P0').length,
  };
}
