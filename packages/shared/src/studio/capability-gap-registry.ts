import { z } from 'zod';

export const CapabilityStatusSchema = z.enum([
  'missing',
  'stub',
  'partial',
  'production_ready',
]);

export const CapabilityPrioritySchema = z.enum(['P0', 'P1', 'P2', 'P3']);

export const StudioCapabilitySchema = z.object({
  id: z.string(),
  stratum: z.string(),
  title: z.string(),
  status: CapabilityStatusSchema,
  priority: CapabilityPrioritySchema,
  maturity_pct: z.number().min(0).max(100),
  problem: z.string(),
  target: z.string(),
  owner_packages: z.array(z.string()),
  agent_roles: z.array(z.string()).default([]),
  blocking_for: z.array(z.string()).default([]),
  implementation_notes: z.array(z.string()).default([]),
});

export type StudioCapability = z.infer<typeof StudioCapabilitySchema>;

